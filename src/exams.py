"""CBT模試のデータ。build.py から EXAMS を読み込む。

ブロックは2種類だけ。
  je    … 仕訳（借方科目・金額／貸方科目・金額の表）。全問正解で pt、部分点なし
  sheet … 答案用紙の穴埋め。fields の1欄ごとに pt

答案用紙のHTMLは f(key) で欄を埋め込む。値はJS側が textContent で差し込む。
"""

SYL = "2026"


def f(k):
    return '<span class="fld" data-f="%s">　</span>' % k


def row(*cells):
    return "<tr>" + "".join(cells) + "</tr>"


def th(t, cls=""):
    return '<th class="%s">%s</th>' % (cls, t)


def td(t, cls=""):
    return '<td class="%s">%s</td>' % (cls, t)


def sheet(caption, head, body):
    return ('<div class="esheet"><div class="ecap">%s</div><table>%s%s</table></div>'
            % (caption, head, body))


# 単純な2列（項目・金額）の答案用紙
def two(caption, rows, unit="単位：円"):
    head = row(th("項目"), th(unit, "r"))
    body = "".join(row(td(a), td(b, "r num")) for a, b in rows)
    return sheet(caption, head, body)


